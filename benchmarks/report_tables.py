#!/usr/bin/env python3
"""Render the README benchmark tables from benchmarks/results.json (single source of truth).

``python benchmarks/report_tables.py`` prints the Markdown; ``--write`` replaces the block
between the BENCH-TABLES markers in README.md. A test checks README matches results.json.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- BENCH-TABLES:START (generated by benchmarks/report_tables.py; do not edit) -->"
END = "<!-- BENCH-TABLES:END -->"
NAMES = {
    "oes_latch": "OES latch",
    "rolling_zscore": "Rolling z-score",
    "cusum": "CUSUM",
    "isolation_forest": "IsolationForest (seed 42)",
}
DETS = tuple(NAMES)
BASES = ("rolling_zscore", "cusum", "isolation_forest")


def _f(v, nd: int = 3) -> str:
    if v is None:
        return "—"
    if isinstance(v, float) and v != 0 and abs(v) < 10**-nd:
        return f"{v:.1e}"
    return f"{v:.{nd}f}"


def _w(v: float) -> str:
    return f"{v:g}"


def render(report: dict) -> str:
    s32 = report["summary"]["32"]
    agg = s32["aggregate"]
    ref = s32["reference"]
    out: list[str] = []
    a = out.append

    a(
        f"**Main result — block 32 (OES-32 contract), {s32['series_scored']} scored series** "
        "(REPORTED; means/medians over series; wins = series where the detector has the best "
        "value, ties shared):"
    )
    a("")
    a(
        "| Detector | Threshold rule | Mean F1 | Median F1 | Mean AP | Median AP | Mean P | "
        "Mean R | Flag rate | F1 wins | AP wins |"
    )
    a("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for mode, label in (
        ("calibrated", "warm-up q0.99"),
        ("trimmed", "trimmed warm-up q0.99"),
    ):
        for d in DETS:
            e = agg[mode][d]
            name = NAMES[d] + (" (self-calibrated τ)" if d == "oes_latch" else "")
            a(
                f"| {name} | {label} | {_f(e['mean_f1'])} | {_f(e['median_f1'])} | "
                f"{_f(e['mean_ap'])} | {_f(e['median_ap'])} | {_f(e['mean_precision'])} | "
                f"{_f(e['mean_recall'])} | {_f(e['mean_flag_rate'])} | "
                f"{_w(agg[mode]['wins_f1'][d])} | {_w(agg[mode]['wins_ap'][d])} |"
            )
    e = agg["default_tau"]["oes_latch"]
    a(
        f"| OES latch | fixed τ = 0.50 (untuned) | {_f(e['mean_f1'])} | {_f(e['median_f1'])} | "
        f"{_f(e['mean_ap'])} | {_f(e['median_ap'])} | {_f(e['mean_precision'])} | "
        f"{_f(e['mean_recall'])} | {_f(e['mean_flag_rate'])} | — | — |"
    )
    a(
        f"| *Reference: flag every block* | — | {_f(ref['flag_all_mean_f1'])} | "
        f"{_f(ref['flag_all_median_f1'])} | — | — | — | 1.000 | 1.000 | — | — |"
    )
    a(
        f"| *Reference: random ranking* | — | — | — | {_f(ref['mean_prevalence_random_ap'])} "
        "(= prevalence) | — | — | — | — | — | — |"
    )
    a("")

    a(
        "**Paired comparison, OES latch minus baseline, block 32** (REPORTED; bootstrap over "
        "series, 10,000 resamples, seed 42; Wilcoxon signed-rank two-sided, Holm-adjusted over "
        "the 3 baselines):"
    )
    a("")
    a(
        "| Thresholds | Metric | vs | Mean diff | 95% CI | Latch better / worse / tie | "
        "Wilcoxon p | Holm p |"
    )
    a("|---|---|---|---:|---|---:|---:|---:|")
    ps = s32["paired_stats"]
    for mode in ("calibrated", "trimmed"):
        for key in ("f1", "ap"):
            for b in BASES:
                c = ps[mode][key][b]
                lo, hi = c["bootstrap_95ci_mean_diff"]
                a(
                    f"| {mode} | {key.upper()} | {NAMES[b]} | {c['mean_diff']:+.3f} | "
                    f"[{lo:+.3f}, {hi:+.3f}] | {c['latch_better']} / {c['latch_worse']} / "
                    f"{c['ties']} | {_f(c['wilcoxon_p'])} | {_f(c['wilcoxon_p_holm'])} |"
                )
    c = ps["default_tau_vs_cusum_calibrated_f1"]
    lo, hi = c["bootstrap_95ci_mean_diff"]
    a(
        f"| τ = 0.50 vs calibrated | F1 | CUSUM | {c['mean_diff']:+.3f} | [{lo:+.3f}, {hi:+.3f}] "
        f"| — | {_f(c['wilcoxon_p'])} | — |"
    )
    a("")

    a("**Oracle best-F1 per series** (REPORTED, **TUNED on test labels** — optimistic):")
    a("")
    a("| Detector | Mean F1 | Median F1 | F1 wins |")
    a("|---|---:|---:|---:|")
    for d in DETS:
        e = agg["oracle"][d]
        a(
            f"| {NAMES[d]} | {_f(e['mean_f1'])} | {_f(e['median_f1'])} | "
            f"{_w(agg['oracle']['wins_f1'][d])} |"
        )
    ts = s32["tau_sweep_tuned"]
    tau05 = dict(zip(ts["tau"], ts["mean_f1"], strict=True))[0.5]
    a("")
    a(
        f"Single global τ sweep (0.25–10.00, **TUNED** on test labels): best τ = "
        f"{ts['best_tau']:g} with mean F1 {_f(ts['best_mean_f1'])} (τ = 0.50: {_f(tau05)})."
    )
    a("")

    a("**By NAB folder, block 32, warm-up q0.99** (REPORTED; mean F1 / mean AP):")
    a("")
    a("| Folder | n | " + " | ".join(NAMES[d] for d in DETS) + " |")
    a("|---|---:|" + "---|" * len(DETS))
    for fo, v in s32["by_folder"].items():
        cells = [
            f"{_f(v['calibrated_mean_f1'][d])} / {_f(v['calibrated_mean_ap'][d])}" for d in DETS
        ]
        a(f"| {fo} | {v['n']} | " + " | ".join(cells) + " |")
    a("")

    a(
        "**Block-size sensitivity** (REPORTED; 16 and 64 are **not** the OES-32 contract; the "
        "series sets differ because short series lack warm-up blocks at 64):"
    )
    a("")
    a("| Block | Series | Detector | Mean F1 (warm-up q0.99) | Mean AP | F1 wins | Flag-all F1 |")
    a("|---:|---:|---|---:|---:|---:|---:|")
    for b in ("16", "32", "64"):
        sb = report["summary"][b]
        for d in DETS:
            e = sb["aggregate"]["calibrated"][d]
            a(
                f"| {b} | {sb['series_scored']} | {NAMES[d]} | {_f(e['mean_f1'])} | "
                f"{_f(e['mean_ap'])} | {_w(sb['aggregate']['calibrated']['wins_f1'][d])} | "
                f"{_f(sb['reference']['flag_all_mean_f1'])} |"
            )
    a("")

    rows = [v["blocks"]["32"] for v in report["series"].values() if "32" in v["blocks"]]
    c = [r["counts"] for r in rows]
    a(
        "**Warm-up contamination, block 32** (REPORTED; labels used only to count): "
        f"{sum(x['positive_blocks_warmup'] > 0 for x in c)} of {len(c)} evaluated series have "
        f"labelled anomalies in the warm-up ({sum(x['positive_blocks_warmup'] for x in c)} "
        f"positive of {sum(x['blocks_warmup'] for x in c)} warm-up blocks). Label-free trimming "
        f"removed {sum(x['blocks_warmup'] - x['blocks_warmup_after_trim'] for x in c)} warm-up "
        "blocks, leaving "
        f"{sum(x['positive_blocks_warmup_after_trim'] for x in c)} positive blocks."
    )
    a("")

    seeds = s32["iforest_seeds"]
    a(
        "**IsolationForest seed robustness, block 32** (REPORTED; seeds "
        + ", ".join(seeds["calibrated"]["per_seed"])
        + "): mean F1 range "
        + f"{_f(seeds['calibrated']['mean_f1_range'][0])}–"
        + f"{_f(seeds['calibrated']['mean_f1_range'][1])}, mean AP range "
        + f"{_f(seeds['calibrated']['mean_ap_range'][0])}–"
        + f"{_f(seeds['calibrated']['mean_ap_range'][1])} (warm-up q0.99); "
        + f"trimmed: F1 {_f(seeds['trimmed']['mean_f1_range'][0])}–"
        + f"{_f(seeds['trimmed']['mean_f1_range'][1])}, AP "
        + f"{_f(seeds['trimmed']['mean_ap_range'][0])}–{_f(seeds['trimmed']['mean_ap_range'][1])}."
    )
    a("")

    sp = s32["speed"]
    a(
        f"**Latch speed, block 32** (REPORTED; {sp['blocks']:,} blocks, best of 3, this machine): "
        f"pure-Python `block_score` {sp['python_block_score_us_per_block']:.2f} µs/block → "
        f"vectorised `benchmarks/fast_score.block_scores` "
        f"{sp['numpy_block_scores_us_per_block']:.2f} µs/block ({sp['speedup']:.1f}× faster), "
        "with bit-identical scores on every block."
    )

    nab = report.get("nab_score")
    a("")
    if nab is None:
        a("**NAB official score:** not computed.")
    else:
        a(
            f"**NAB official scorer** on the {nab['series']}-series sub-corpus (REPORTED; see the "
            "caveats below — not comparable to the public NAB scoreboard):"
        )
        a("")
        a("| Detector | Thresholds | Standard | Reward low FP | Reward low FN |")
        a("|---|---|---:|---:|---:|")
        for d, v in nab["normalized_scores"].items():
            ours = d in NAMES
            name = NAMES[d] if ours else f"NAB `{d}`"
            how = "warm-up q0.99, no label use" if ours else "NAB-optimised (labels)"
            a(
                f"| {name} | {how} | {v['standard']:.2f} | {v['reward_low_FP_rate']:.2f} | "
                f"{v['reward_low_FN_rate']:.2f} |"
            )
    return "\n".join(out)


def splice(readme: str, tables: str) -> str:
    i, j = readme.index(START), readme.index(END)
    return readme[: i + len(START)] + "\n" + tables + "\n" + readme[j:]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--results", type=Path, default=ROOT / "benchmarks" / "results.json")
    p.add_argument("--readme", type=Path, default=ROOT / "README.md")
    p.add_argument("--write", action="store_true")
    args = p.parse_args(argv)
    tables = render(json.loads(args.results.read_text(encoding="utf-8")))
    if args.write:
        text = args.readme.read_text(encoding="utf-8")
        args.readme.write_text(splice(text, tables), encoding="utf-8")
    else:
        print(tables)
    return 0


if __name__ == "__main__":
    sys.exit(main())
